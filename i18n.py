class I18nManager:
    _instance = None
    current_lang = "en"

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(I18nManager, cls).__new__(cls)
            cls._instance.current_lang = "en"
        return cls._instance

    def _detect_system_language(self) -> str:
        try:
            for env_var in ("LC_ALL", "LC_MESSAGES", "LANG"):
                val = os.environ.get(env_var)
                if val:
                    lang_code = val.split(".")[0].split("_")[0].lower()
                    if lang_code in SUPPORTED_LANGUAGES:
                        return lang_code

            loc = locale.getlocale(locale.LC_MESSAGES)[0] or locale.getlocale()[0]
            if loc:
                lang_code = loc.split("_")[0].lower()
                if lang_code in SUPPORTED_LANGUAGES:
                    return lang_code
        except Exception as e:
            logger.debug("System language detection error: %s", e)
        return "en"

    def get_language(self) -> str:
        return getattr(self, "current_lang", "en")

    def set_language(self, lang_code: str):
        if lang_code == "auto":
            self.current_lang = self._detect_system_language()
        elif lang_code in SUPPORTED_LANGUAGES:
            self.current_lang = lang_code
        else:
            self.current_lang = "en"

    def get_text(self, _msg_key: str, **kwargs) -> str:
        lang_dict = TRANSLATIONS.get(self.current_lang, TRANSLATIONS.get("en", {}))
        text = lang_dict.get(_msg_key, TRANSLATIONS.get("en", {}).get(_msg_key, _msg_key))
        if kwargs:
            try:
                text = text.format(**kwargs)
            except (KeyError, IndexError, ValueError) as e:
                logger.debug("String format failed for key '%s': %s", _msg_key, e)
        return text

i18n = I18nManager()

def t(_msg_key: str, **kwargs) -> str:
    return i18n.get_text(_msg_key, **kwargs)

def get_current_language() -> str:
    return i18n.get_language()
